// Generates sw.js: collects the app's assets, stamps a cache name from the app version, and
// writes a cache-first service worker. Run after adding/removing assets or bumping the version:
//   node tools/build-sw.js   (npm run build:sw)
// No build step for the app itself — this is a one-off generator, like tools/make-sounds.js.

import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

function walk(dir, acc = []) {
  for (const name of readdirSync(join(ROOT, dir))) {
    const rel = `${dir}/${name}`;
    if (statSync(join(ROOT, rel)).isDirectory()) walk(rel, acc);
    else acc.push(rel);
  }
  return acc;
}

const rootFiles = ['index.html', 'manifest.webmanifest', 'icon-192.png', 'icon-512.png', 'apple-touch-icon.png'];
const assets = ['./', ...rootFiles, ...walk('css'), ...walk('js')].map((p) => (p === './' ? p : `./${p}`));

const version = readFileSync(join(ROOT, 'js/version.js'), 'utf8').match(/VERSION\s*=\s*'([^']+)'/)[1];
const CACHE = `zirkel-dojo::${version}`;

const sw = `// GENERATED by tools/build-sw.js — do not edit by hand. Run \`npm run build:sw\` after asset or version changes.
const CACHE = ${JSON.stringify(CACHE)};
const ASSETS = ${JSON.stringify(assets, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)));
  // No skipWaiting: a freshly deployed worker waits until the app asks it to take over, so the
  // "Neue Version verfügbar" hint can show first (and the app can hold it back during a training).
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) if (name !== CACHE) await caches.delete(name);
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'skipWaiting') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(cacheFirst(request));
});

async function cacheFirst(request) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(request, { ignoreSearch: true });
  if (cached) return cached;
  try {
    const response = await fetch(request);
    if (response && response.ok && response.type === 'basic') cache.put(request, response.clone());
    return response;
  } catch (err) {
    if (request.mode === 'navigate') {
      const shell = (await cache.match('./index.html')) || (await cache.match('./'));
      if (shell) return shell;
    }
    throw err;
  }
}
`;

writeFileSync(join(ROOT, 'sw.js'), sw);
console.log(`sw.js written: ${assets.length} assets, cache "${CACHE}"`);
