// Converts the body graphic of react-native-body-highlighter (MIT, © 2022 ELABBASSI Hicham)
// into js/data/body.js: plain SVG path data, no React. Run once per upstream update:
//
//   git clone https://github.com/HichamELBSI/react-native-body-highlighter <dir>
//   node tools/make-body.mjs <dir>
//
// The upstream files are read as text only (nothing from them is executed). Taken over: the
// male figure, front and back, with its outline. Left/right halves of a region are merged,
// because exercises here do not distinguish sides.

import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const src = process.argv[2];
if (!src) {
  console.error('Aufruf: node tools/make-body.mjs <Pfad zum Checkout von react-native-body-highlighter>');
  process.exit(1);
}
const read = (file) => readFileSync(join(src, file), 'utf8');

// Cropped to the figure (getBBox over all paths: x 49..679 / 769..1399, y 96..1352; 4 units of air).
// Upstream draws both sides into one 1448 × 1448 sheet, the back shifted right by 724.
const VIEWBOX = { front: '45 92 639 1264', back: '764 92 639 1264' };

/** [[slug, d], …] in upstream order; every path of a region joined into one `d`. */
function parts(file) {
  const text = read(file);
  const out = [];
  const marks = [...text.matchAll(/slug:\s*"([^"]+)"/g)];
  marks.forEach((m, i) => {
    const chunk = text.slice(m.index, marks[i + 1]?.index ?? text.length);
    const paths = [...chunk.matchAll(/"([Mm][^"]*)"/g)].map((p) => p[1].trim());
    if (!paths.length) throw new Error(`${file}: keine Pfade für ${m[1]}`);
    out.push([m[1], paths.join('')]);
  });
  return out;
}

// the two outlines sit in the wrapper component: front first, back second
const outlines = [...read('components/SvgMaleWrapper.tsx').matchAll(/\bd="(M [^"]+)"/g)].map((m) =>
  m[1].replace(/\s+/g, ' ').trim());
if (outlines.length !== 2) throw new Error(`Erwartet 2 Umrisse, gefunden ${outlines.length}`);

let commit = 'unbekannt';
try {
  commit = execFileSync('git', ['-C', src, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
} catch { /* not a git checkout */ }

const side = (name, file, outline) => `  ${name}: {
    viewBox: '${VIEWBOX[name]}',
    outline: '${outline}',
    parts: [
${parts(file).map(([slug, d]) => `      ['${slug}', '${d}'],`).join('\n')}
    ],
  },`;

const out = `// GENERATED by tools/make-body.mjs, do not edit by hand.
// Body graphic (male figure, front and back) from react-native-body-highlighter,
// https://github.com/HichamELBSI/react-native-body-highlighter (commit ${commit}),
// MIT License, Copyright (c) 2022 ELABBASSI Hicham. Full text: THIRD-PARTY-NOTICES.md.
// parts: [region name, SVG path data]. The region names match js/data/muscles.js; the other
// names (head, hair, hands, knees, ankles, feet) only complete the figure.

export const BODY = Object.freeze({
${side('front', 'assets/bodyFront.ts', outlines[0])}
${side('back', 'assets/bodyBack.ts', outlines[1])}
});
`;

const target = join(fileURLToPath(new URL('..', import.meta.url)), 'js', 'data', 'body.js');
writeFileSync(target, out);
console.log(`${target}: ${(out.length / 1024).toFixed(1)} kB, Quelle ${commit}`);
